"""Rewrite a stylesheet so every colour is a CSS variable and every font-size scales.

    python scripts/themeify-css.py frontend/src/styles.css frontend/src/palette.ts
    python scripts/themeify-css.py extension/src/sidepanel.css extension/src/palette.ts

Each `#rrggbb` (or `#rgb`, `#rrggbbaa`) becomes `var(--c-rrggbb)`, a `:root` block with the
light-mode defaults is inserted after any @import lines, and `font-size: Npx` becomes
`font-size: calc(Npx * var(--ts, 1))`. The list of colours is written to a TypeScript module so
`theme.ts` can recompute the variables for dark mode and other palettes. Safe to re-run: colours
already wrapped in var() are left alone and the defaults block is regenerated.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HEX = re.compile(r"#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})(?![0-9a-fA-F\w-])")
DEFAULTS = re.compile(r"/\* theme defaults \*/:root\{[^}]*\}\n?")
FONT_SIZE = re.compile(r"font-size:\s*(\d+(?:\.\d+)?)px(?!\s*\*)")


def normalise(hex_value: str) -> str:
    h = hex_value.lower()
    if len(h) == 4:
        h = "#" + "".join(ch * 2 for ch in h[1:])
    return h


def themeify(css: str) -> tuple[str, list[str]]:
    css = DEFAULTS.sub("", css)
    hexes: list[str] = []
    # Recover colours that are already variables so the defaults block stays complete.
    for found in re.findall(r"var\(--c-([0-9a-f]{6}|[0-9a-f]{8})\)", css):
        if f"#{found}" not in hexes:
            hexes.append(f"#{found}")

    def replace(match: re.Match[str]) -> str:
        h = normalise(match.group(0))
        if h not in hexes:
            hexes.append(h)
        return f"var(--c-{h[1:]})"

    css = HEX.sub(replace, css)
    css = FONT_SIZE.sub(r"font-size:calc(\1px * var(--ts, 1))", css)
    defaults = "/* theme defaults */:root{" + ";".join(f"--c-{h[1:]}:{h}" for h in hexes) + ";--ts:1}\n"
    lines = css.split("\n")
    insert_at = 0
    while insert_at < len(lines) and (lines[insert_at].startswith("@import") or not lines[insert_at].strip()):
        insert_at += 1
    lines.insert(insert_at, defaults.rstrip("\n"))
    return "\n".join(lines), hexes


def main() -> None:
    css_path, ts_path = Path(sys.argv[1]), Path(sys.argv[2])
    css, hexes = themeify(css_path.read_text(encoding="utf-8"))
    css_path.write_text(css, encoding="utf-8")
    body = ",\n".join(f"  '{h}'" for h in hexes)
    ts_path.write_text(
        "// Generated by scripts/themeify-css.py; the colours the stylesheet references as var(--c-<hex>).\n"
        f"export const PALETTE_HEXES: readonly string[] = [\n{body},\n];\n",
        encoding="utf-8",
    )
    print(f"{css_path}: {len(hexes)} colours -> {ts_path}")


if __name__ == "__main__":
    main()
